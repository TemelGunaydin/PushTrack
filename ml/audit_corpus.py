class IntegrityError(RuntimeError):
    pass


def require(condition, reason):
    if not condition:
        raise IntegrityError(reason)


def byte_lines(data):
    parts = data.split(b"\n")
    return [p + b"\n" for p in parts[:-1]] + ([parts[-1]] if parts[-1] else [])


def apply_section(section, original):
    """Independently apply unified hunks to exact bytes, including missing final LF."""
    lines = byte_lines(section)
    old = byte_lines(original)
    result, cursor, index, count = [], 0, 0, 0
    while index < len(lines):
        line = lines[index]
        if not line.startswith(b"@@ "):
            require(count == 0, "unexpected_patch_line")
            index += 1
            continue
        match = HUNK.fullmatch(line.decode("utf-8").rstrip("\n"))
        require(match is not None, "invalid_hunk_header")
        start_old, amount_old = int(match[1]), int(match[2] or "1")
        start_new, amount_new = int(match[3]), int(match[4] or "1")
        position = start_old - 1 if amount_old else start_old
        destination = start_new - 1 if amount_new else start_new
        require(cursor <= position <= len(old), "invalid_old_hunk_position")
        result.extend(old[cursor:position])
        cursor = position
        require(len(result) == destination, "invalid_new_hunk_position")
        index += 1
        used_old = used_new = 0
        while index < len(lines) and not lines[index].startswith(b"@@ "):
            token = lines[index]
            require(token[:1] in (b" ", b"+", b"-"), "invalid_patch_body")
            content = token[1:]
            index += 1
            if index < len(lines) and lines[index] == b"\\ No newline at end of file\n":
                require(content.endswith(b"\n"), "invalid_final_newline_marker")
                content = content[:-1]
                index += 1
            if token[:1] in (b" ", b"-"):
                require(cursor < len(old) and old[cursor] == content, "patch_does_not_match_original")
                cursor += 1
                used_old += 1
            if token[:1] in (b" ", b"+"):
                result.append(content)
                used_new += 1
        require((used_old, used_new) == (amount_old, amount_new), "hunk_count_mismatch")
        count += 1
    require(count > 0, "missing_hunk")
    result.extend(old[cursor:])
    return b"".join(result)


def parse_batch(raw, expected):
    result, offset = {}, 0
    while offset < len(raw):
        end = raw.find(b"\n", offset)
        require(end >= 0, "incomplete_git_batch_header")
        fields = raw[offset:end].split()
        require(len(fields) == 3 and fields[2].isdigit(), "missing_cached_git_object")
        sha, kind, size = fields[0].decode(), fields[1].decode(), int(fields[2])
        start = end + 1
        content = raw[start:start + size]
        require(len(content) == size and raw[start + size:start + size + 1] == b"\n", "incomplete_git_object")
        actual = hashlib.sha1(kind.encode() + b" " + str(size).encode() + b"\0" + content).hexdigest()
        require(sha == actual and sha not in result, "git_object_identity")
        result[sha] = (kind, content)
        offset = start + size + 1
    require(set(result) == set(expected), "git_batch_coverage")
    return result


class CachedGit(GitSource):
    """Reuse the bounded runner, but never create repositories or access the network."""
    def __init__(self, directory, temporary):
        require((directory / "HEAD").is_file(), "missing_cached_repository")
        self.directory, self.temporary = directory, temporary
        self.stop, self.deadline, self.blobs = threading.Event(), time.monotonic() + 1800, {}
        self.env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
        self.env.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull, GIT_TERMINAL_PROMPT="0",
                        GCM_INTERACTIVE="Never", GIT_NO_LAZY_FETCH="1", GIT_LITERAL_PATHSPECS="1",
                        TEMP=str(temporary), TMP=str(temporary))
        self.base = [shutil.which("git"), "--no-replace-objects", "-c", "core.hooksPath=NUL",
                     "-c", "core.fsmonitor=false", "-c", "gc.auto=0", "-c", "maintenance.auto=false",
                     "-c", "protocol.allow=never", "-c", "protocol.https.allow=never", "-c", "protocol.http.allow=never",
                     "-C", str(directory)]

    def run(self, *args, **kwargs):
        require(args and args[0] in {"cat-file", "diff-tree", "ls-tree", "patch-id", "fsck"}, "read_only_git_command")
        return super().run(*args, **kwargs)


def checked_evidence(root, category, entry):
    require(re.fullmatch(r"[0-9a-f]{64}", entry["sha256"]) is not None, "invalid_evidence_hash")
    data = (root / category / (entry["sha256"] + ".txt")).read_bytes()
    require(digest(data) == entry["sha256"], "evidence_sha256")
    blob = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
    require(blob == entry["blob_sha"], "evidence_git_blob")
    return data


def label_flags(message, diff):
    flags = set()
    if EMAIL.search(diff):
        flags.add("email_like_input_context")
    if re.search(r"\b(?:thanks|thank you|credits?|co-authored|signed-off|reviewed-by)\b", message, re.I):
        flags.add("non_diff_attribution_target")
    if GENERIC_DOC.fullmatch(CONVENTIONAL.sub("", message)):
        flags.add("generic_documentation_target")
    return flags


def changed_text(diff):
    return "\n".join(line for line in diff.split("\n")
                     if line[:1] in ("+", "-") and not line.startswith(("+++", "---")))


def change_shingles(diff):
    tokens = re.findall(r"\w+|[^\w\s]", changed_text(diff))
    if len(tokens) < 40:
        return set()
    return {tuple(tokens[i:i + 5]) for i in range(len(tokens) - 4)}


def near_overlap(rows):
    """Conservative path-independent changed-token similarity; findings are holds."""
    references, inverted = {}, defaultdict(set)
    for row in rows:
        if row["split"] == "validation":
            features = change_shingles(row["diff"])
            references[row["commit_id"]] = features
            for feature in features:
                inverted[feature].add(row["commit_id"])
    hits = []
    for row in rows:
        if row["split"] != "train":
            continue
        features = change_shingles(row["diff"])
        candidates = Counter(sha for feature in features for sha in inverted.get(feature, ()))
        for sha, shared in candidates.items():
            union = len(features) + len(references[sha]) - shared
            if union and shared / union >= 0.85:
                hits.append({"train_commit": row["commit_id"], "validation_commit": sha,
                             "changed_token_jaccard": shared / union})
    return hits


def audit_repo(job, root, workspace):
    repo, rows = job
    path = root / "repos" / hashlib.sha256(repo.encode()).hexdigest()[:24]
    git = CachedGit(path, workspace / ".tmp")
    result = {"repo_id": repo, "rows": [], "errors": [], "fsck": "pending"}
    try:
        git.run("fsck", "--full", "--no-reflogs", "--no-dangling", limit=1_000_000)
        result["fsck"] = "pass"
        requested = sorted({value for row in rows for value in (row["commit_id"], row["parent_id"])})
        objects = parse_batch(git.run("cat-file", "--batch", data=("\n".join(requested) + "\n").encode(), limit=10_000_000), requested)
        patch_input = b"".join(("commit " + row["commit_id"] + "\n" + row["diff"]).encode() for row in rows)
        patch_ids = {parts[1]: parts[0] for line in git.run("patch-id", "--stable", data=patch_input, limit=100_000).decode().splitlines() if len(parts := line.split()) == 2}
        require(set(patch_ids) == {r["commit_id"] for r in rows}, "patch_id_coverage")
        tokenizer = OfficialTokenizer(workspace / "runs" / "tokenizer-0002" / "codet5-small")
        for row in rows:
            try:
                sha, parent = row["commit_id"], row["parent_id"]
                require(objects[sha][0] == objects[parent][0] == "commit", "commit_object_type")
                require(parse_commit(objects[sha][1], row["message"])[0] == parent, "parent_identity")
                require(patch_ids[sha] == row["patch_id"], "stable_patch_identity")
                require(digest(row["diff"].encode()) == row["diff_sha256"], "diff_sha256")
                require(subject(row["message"]) == row["message"], "subject_policy")
                require(not SECRET.search(row["diff"]), "secret_in_diff")
                lengths = (len(tokenizer.encode(PREFIX + row["diff"]).ids), len(tokenizer.encode(row["message"]).ids))
                require(lengths == (row["input_tokens"], row["target_tokens"]), "token_length_identity")
                require(lengths[0] <= 512 and lengths[1] <= 64, "token_budget")
                files = parse_changes(git.run("diff-tree", "--no-commit-id", "--raw", "-r", "-z", "--no-renames", "--no-abbrev", parent, sha))
                require([f["filename"] for f in files] == row["files"], "complete_changed_file_list")
                expected_snapshots = {(revision, f["filename"]): f[side] for revision, side in ((parent, "old_blob"), (sha, "new_blob")) for f in files if f[side] != ZERO}
                recorded = {(e["revision"], e["path"]): e for e in row["source_file_screening"]}
                require(len(recorded) == len(row["source_file_screening"]) and set(recorded) == set(expected_snapshots), "snapshot_coverage")
                flags, snapshots = label_flags(row["message"], row["diff"]), {}
                for key, blob in expected_snapshots.items():
                    entry = recorded[key]
                    require(entry["blob_sha"] == blob, "snapshot_matches_original_tree")
                    content = checked_evidence(root, "source-files", entry)
                    text = content.decode("utf-8")
                    require(not SECRET.search(text), "secret_in_source")
                    declarations = re.findall(r"SPDX-License-Identifier:\s*([^\n\r]+)", text)
                    require(all(value.strip(" */\t") == "MIT" for value in declarations), "conflicting_SPDX")
                    require(not re.search(r"GNU (?:Lesser |Affero )?General Public License|Apache License|Mozilla Public License", text, re.I), "conflicting_source_notice")
                    if GENERATED_HEADER.search(text[:4096]):
                        flags.add("generated_source_header")
                    snapshots[key] = content
                sections = re.split(r"(?m)(?=^diff --git )", row["diff"])
                require(sections[0] == "" and len(sections) - 1 == len(files), "patch_file_coverage")
                for file, section in zip(files, sections[1:]):
                    name = file["filename"]
                    require(section.split("\n", 1)[0] == f"diff --git a/{name} b/{name}", "patch_path_identity")
                    applied = apply_section(section.encode(), snapshots.get((parent, name), b""))
                    require(applied == snapshots.get((sha, name), b""), "patch_not_complete_original_change")
                expected_notices = {}
                paths = license_paths(files)
                for revision in (parent, sha):
                    expected_notices.update({(revision, name): blob for name, blob in parse_licenses(git.run("ls-tree", "-r", "-z", revision, "--", *paths)).items()})
                notices = {(e["revision"], e["path"]): e for e in row["source"]["license_evidence"]}
                require(len(notices) == len(row["source"]["license_evidence"]) and set(notices) == set(expected_notices), "notice_coverage")
                for key, blob in expected_notices.items():
                    require(notices[key]["blob_sha"] == blob, "notice_matches_original_tree")
                    check_mit_notice(checked_evidence(root, "licenses", notices[key]))
                result["rows"].append({"commit_id": sha, "flags": sorted(flags), "file_pairs": [(f["old_blob"], f["new_blob"]) for f in files]})
            except Exception as error:
                result["errors"].append({"commit_id": row["commit_id"], "error": f"{type(error).__name__}: {error}"})
    except Exception as error:
        result["errors"].append({"error": f"{type(error).__name__}: {error}"})
    return result


def family_identity(value):
    require(type(value.get("id")) is int and value["id"] > 0 and isinstance(value.get("fork"), bool), "repository_metadata_shape")
    require(value.get("private") is False, "non_public_repository")
    identity(value["full_name"], "a" * 40)
    source = value.get("source") if value["fork"] else value
    require(isinstance(source, dict) and type(source.get("id")) is int and source["id"] > 0, "missing_fork_root")
    identity(source["full_name"], "a" * 40)
    return {"canonical_id": value["id"], "canonical_name": value["full_name"].casefold(),
            "family_id": source["id"], "family_name": source["full_name"].casefold(), "is_fork": value["fork"]}


def audit_families(rows, output):
    network = Network(budget=15_000_000)
    validation = sorted({r["repo_id"] for r in rows if r["split"] == "validation"})
    train = sorted({r["repo_id"] for r in rows if r["split"] == "train"})
    # Interleave both splits so a quota-limited pass does not inspect only validation.
    order = []
    for index in range(max(len(validation), (len(train) + 2) // 3)):
        order.extend(validation[index:index + 1])
        order.extend(train[index * 3:index * 3 + 3])
    result = {"status": "running", "needed": len(order), "repositories": {}, "failures": {}}
    directory = output / "repository-metadata"
    directory.mkdir()
    for repo in order:
        try:
            raw, headers = network.fetch(f"https://api.github.com/repos/{repo}", 1_000_000)
            name = hashlib.sha256(repo.encode()).hexdigest() + ".json"
            (directory / name).write_bytes(raw)
            result["repositories"][repo] = {**family_identity(json.loads(raw)), "response_sha256": digest(raw), "response_file": name}
        except HTTPError as error:
            result["failures"][repo] = f"HTTP {error.code}"
        except Exception as error:
            result.update(status="blocked", stop_reason=f"{type(error).__name__}: {error}")
            break
        result.update(api_requests=network.github_requests, remaining=network.remaining)
        write_progress(output / "families.json", result)
    if result["status"] == "running":
        result["status"] = "complete" if len(result["repositories"]) == len(order) else "incomplete"
    result.update(api_requests=network.github_requests, remaining=network.remaining)
    write_progress(output / "families.json", result)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=Path(r"D:\PushTrackML"))
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if platform.system() != "Windows":
        parser.error("Audit natively on Windows")
    if args.output.exists():
        parser.error("Preserve previous evidence; require new audit output")
    for name in ("TEMP", "TMP", "SQLITE_TMPDIR"):
        os.environ[name] = str(args.workspace / ".tmp")
    root = args.workspace / "data" / "corpus-0001" / "sources-0001"
    require(json.loads((root / "report.json").read_text())["status"] == "targets_reached", "source_pass_not_complete")
    rows, hashes = [], {}
    for split, (count, sha) in INPUTS.items():
        raw = (root / (split + "-pending.jsonl")).read_bytes()
        require(digest(raw) == sha and raw.endswith(b"\n"), "source_export_identity")
        selected = [json.loads(line) for line in raw.splitlines()]
        require(len(selected) == count and all(r["split"] == split and r["training_approved"] is False for r in selected), "source_export_shape")
        rows.extend(selected)
        hashes[split] = sha
    require(len({r["commit_id"] for r in rows}) == len(rows), "duplicate_commit")
    by_repo = defaultdict(list)
    for row in rows:
        identity(row["repo_id"], row["commit_id"])
        by_repo[row["repo_id"].casefold()].append(row)
    require(all(len({r["split"] for r in group}) == 1 for group in by_repo.values()), "repository_split_overlap")
    args.output.mkdir(parents=True)
    provenance = args.output / "provenance"
    provenance.mkdir()
    for name in ("audit_corpus.py", "test_audit_corpus.py", "verify_corpus_sources.py", "continue_pilot.py", "prepare_corpus.py", "download_corpus.py", "compare_tokenizers.py", "prepare_pilot.py", "requirements-data.lock"):
        shutil.copyfile(Path(__file__).parent / name, provenance / name)
    report = {"status": "running", "started_at_utc": dt.datetime.now(dt.UTC).isoformat(), "input_rows": 11000,
              "source_hashes": hashes, "repositories": len(by_repo), "integrity_passed": 0, "integrity_errors": 0,
              "training_approved": False, "test_read": False, "source_sha256": digest(Path(__file__).read_bytes())}
    flags, proofs, errors = defaultdict(set), {}, []
    # Resolve Transformers' lazy imports on the main thread before cold workers.
    # Workers still construct independent tokenizer instances, not a shared backend.
    OfficialTokenizer(args.workspace / "runs" / "tokenizer-0002" / "codet5-small")
    with ThreadPoolExecutor(max_workers=2) as pool, (args.output / "integrity.jsonl").open("x", encoding="utf-8") as log:
        for result in pool.map(lambda job: audit_repo(job, root, args.workspace), sorted(by_repo.items())):
            for proof in result["rows"]:
                proofs[proof["commit_id"]] = proof
                flags[proof["commit_id"]].update(proof["flags"])
            errors.extend(dict(error, repo_id=result["repo_id"]) for error in result["errors"])
            log.write(json.dumps(result) + "\n")
            log.flush()
            report.update(integrity_passed=len(proofs), integrity_errors=len(errors))
            write_progress(args.output / "report.json", report)
            print(f'Integrity: {len(proofs):,}/11,000; errors {len(errors)}; {result["repo_id"]}', flush=True)
    report["errors"] = errors
    if len(proofs) != len(rows) or errors:
        report.update(status="integrity_failed", finished_at_utc=dt.datetime.now(dt.UTC).isoformat())
        write_progress(args.output / "report.json", report)
        raise IntegrityError("integrity_audit_failed; inspect saved evidence")
    # Provenance coordinates and subjects must still match the immutable candidate index.
    db_path = root.parent / "prepared" / "candidates.sqlite3"
    with sqlite3.connect(db_path.as_uri() + "?mode=ro", uri=True) as db:
        for row in rows:
            expected = db.execute("SELECT repo_id,split,shard,row_index,subject FROM candidates WHERE commit_id=?", (row["commit_id"],)).fetchone()
            require(expected == (row["repo_id"], row["split"], row["dataset"]["shard"], row["dataset"]["row_index"], row["message"]), "candidate_provenance_mismatch")
            require(row["dataset"]["name"] == DATASET and row["dataset"]["revision"] == REVISION, "dataset_revision")
    prior = json.loads((root / "quality-review-0001.json").read_text())
    indexed = {r["commit_id"]: r for r in rows}
    for review in prior["reviews"]:
        row = indexed[review["commit_id"]]
        require(row["diff_sha256"] == review["diff_sha256"] and row["message"] == review["original_subject"], "prior_review_identity")
        if review["decision"].startswith("hold_"):
            flags[row["commit_id"]].add("prior_" + review["decision"])
    cross = []
    for field in ("diff_sha256", "patch_id"):
        groups = defaultdict(list)
        for row in rows:
            groups[row[field]].append(row)
        for group in groups.values():
            if len(group) > 1:
                for row in sorted(group, key=lambda r: (r["split"] != "validation", r["commit_id"]))[1:]:
                    flags[row["commit_id"]].add("duplicate_" + field)
                cross.append({"kind": field, "commits": [r["commit_id"] for r in group]})
    val_objects = {value for r in rows if r["split"] == "validation" for value in (r["commit_id"], r["parent_id"])}
    val_pairs = {tuple(pair) for r in rows if r["split"] == "validation" for pair in proofs[r["commit_id"]]["file_pairs"]}
    for repo, group in by_repo.items():
        if group[0]["split"] == "train" and any({r["commit_id"], r["parent_id"]} & val_objects for r in group):
            for row in group:
                flags[row["commit_id"]].add("shared_validation_commit_family")
    for row in rows:
        if row["split"] == "train" and any(tuple(pair) in val_pairs for pair in proofs[row["commit_id"]]["file_pairs"]):
            flags[row["commit_id"]].add("shared_validation_file_change")
    near = near_overlap(rows)
    for hit in near:
        flags[hit["train_commit"]].add("near_validation_change")
    json_write(args.output / "content-overlap.json", {"duplicates": cross, "near_changes": near})
    families = audit_families(rows, args.output)
    family_map = families["repositories"]
    val_families = {family_map[r["repo_id"]]["family_id"] for r in rows if r["split"] == "validation" and r["repo_id"] in family_map}
    for row in rows:
        if row["split"] == "train" and row["repo_id"] in family_map and family_map[row["repo_id"]]["family_id"] in val_families:
            flags[row["commit_id"]].add("github_validation_fork_family")
    eligible, held = Counter(), Counter()
    with (args.output / "holds.jsonl").open("x", encoding="utf-8") as log:
        for split in INPUTS:
            with (args.output / (split + "-screened-pending.jsonl")).open("x", encoding="utf-8", newline="\n") as export:
                for row in (r for r in rows if r["split"] == split):
                    reasons = sorted(flags[row["commit_id"]])
                    if reasons:
                        held[split] += 1
                        log.write(json.dumps({"repo_id": row["repo_id"], "commit_id": row["commit_id"], "split": split, "reasons": reasons}) + "\n")
                    else:
                        eligible[split] += 1
                        export.write(json.dumps(dict(row, review_status="integrity_checked_quality_screened_pending", training_approved=False)) + "\n")
    report.update(status="audit_complete_not_training_ready", family_status=families["status"],
                  family_repositories_checked=len(family_map), family_repositories_needed=len(by_repo),
                  held=dict(held), screened_pending=dict(eligible), flag_counts=dict(Counter(f for values in flags.values() for f in values)),
                  content_duplicate_groups=len(cross), near_change_pairs=len(near),
                  limitations=["Unreviewed labels remain weak supervision, not certified English/faithfulness", "Partial fork metadata cannot establish full separation", "Known notice names and heuristic secret screens are not exhaustive legal/privacy clearance", "Pretraining contamination was not audited"],
                  finished_at_utc=dt.datetime.now(dt.UTC).isoformat())
    report["exports"] = {}
    for path in args.output.glob("*-screened-pending.jsonl"):
        report["exports"][path.name] = {"bytes": path.stat().st_size, "sha256": digest(path.read_bytes())}
    for split, (_, expected) in INPUTS.items():
        require(digest((root / (split + "-pending.jsonl")).read_bytes()) == expected, "source_changed_during_audit")
    write_progress(args.output / "report.json", report)
    print(json.dumps(report, indent=2), flush=True)


if __name__ == "__main__":
    main()
